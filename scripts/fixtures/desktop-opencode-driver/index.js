import { bindBrowserProofTrace } from '../../lib/browser-proof-trace.mjs';
/** CI transport only: forwards requested Agents tools, never fabricates native model output. */
import { writeFileSync, renameSync } from 'node:fs';
import { join } from 'node:path';
import { LlmAdapter, ToolCallId } from '@deepseek-ai/dsh-llm';
export const name = 'dsh-x-desktop-opencode-driver';
export const inject = ['llm'];
const text = m => (m?.content ?? []).filter(b => b.type === 'text').map(b => b.text).join('\n');
function* reply(value) {
  yield { type: 'block-start', index: 0, blockType: 'text' };
  yield { type: 'text-delta', index: 0, text: value };
  yield { type: 'block-end', index: 0, block: { type: 'text', text: value } };
  yield { type: 'finish', reason: { kind: 'stop' } };
}
class Driver extends LlmAdapter {
  providerInfo(provider) { return { id: provider, name: 'Deterministic DSH transport; real OpenCode execution' }; }
  async listModels(provider) { return [{ provider, id: 'transport-only', name: 'Tool router (not a model response)', inputModalities: ['text'] }]; }
  async resolveModel(provider, model) { if (provider !== 'desktop-opencode-driver' || model !== 'transport-only') throw Error('Driver route only'); return (await this.listModels(provider))[0]; }
  async *stream(options) {
    const at = options.messages.findLastIndex(m => m.role === 'user' && (!m.source || m.source.kind === 'user'));
    let request;
    try { request = JSON.parse(text(options.messages[at])); } catch { yield* reply('DSH transport ready. Native OpenCode replies will appear in Agents. No answer is generated by this router.'); return; }
    if (!/^[a-z0-9-]{1,64}$/.test(request.id) || !['dsh_x_agents_inspect','dsh_x_agents_models','dsh_x_agents_run'].includes(request.tool)) throw Error('Invalid real-provider test request');
    const subsequent = options.messages.slice(at + 1), results = subsequent.filter(m => m.role === 'tool');
    const id = ToolCallId(`opencode-proof-${request.id}`);
    if (results.length) {
      if (results.length !== 1 || results[0].toolCallId !== id) throw Error('Unexpected tool result identity; no replay');
      const result = { id: request.id, isError: results[0].isError === true, text: text(results[0]) };
      const file = join(process.env.DSH_OPENCODE_PROOF_RESULTS, `${request.id}.json`);
      writeFileSync(`${file}.tmp`, JSON.stringify(result)); renameSync(`${file}.tmp`, file);
      yield* reply('Requested native operation returned. Inspect its actual result in Agents. This transport did not generate or alter the native answer.'); return;
    }
    if (subsequent.some(m => m.content?.some(b => b.type === 'tool-call'))) throw Error('Missing result; refusing replay');
    yield { type: 'block-start', index: 0, blockType: 'tool-call' };
    yield { type: 'tool-call-delta', index: 0, id, name: request.tool, argumentsDelta: JSON.stringify(request.arguments ?? {}) };
    yield { type: 'block-end', index: 0, block: { type: 'tool-call', id, name: request.tool, arguments: JSON.stringify(request.arguments ?? {}) } };
    yield { type: 'finish', reason: { kind: 'tool-calls' } };
  }
}
export function apply(ctx) { bindBrowserProofTrace(ctx, process.env.DSH_OPENCODE_PROOF_RESULTS); ctx.effect(() => ctx.llm.registerAdapter(['desktop-opencode-driver'], new Driver())); }
